// Builds the "Created Firefox-Port" badge icon: Mozilla's Firefox logo fused
// with the RoValra mark (the Rv medallion sits where the Firefox globe is),
// encoded as a CSP-safe data: URI — roblox.com's img-src allows data: but
// blocks remote hosts and extension URLs.
//
// Run: node scripts/generate-firefox-port-badge.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The Firefox root tag is kept byte-for-byte (rebuilding it was found to
// break rendering of the gradient paths); only the medallion is appended.
const firefoxSvg = readFileSync(
    join(root, 'scripts/firefox-logo.svg'),
    'utf8',
).trim();

const rovalraPng = readFileSync(
    join(root, 'public/Assets/icon-128.png'),
).toString('base64');

const overlay =
    `<g>` +
    `<circle cx="256" cy="256" r="128" fill="#170a2b" opacity="0.65"/>` +
    `<circle cx="256" cy="256" r="128" fill="none" stroke="#ffffff" stroke-width="7"/>` +
    `<image href="data:image/png;base64,${rovalraPng}" x="158" y="158" width="196" height="196"/>` +
    `</g>`;

const composed = firefoxSvg.replace(/<\/svg>\s*$/, `${overlay}</svg>`);

// encodeURIComponent is required: the Firefox artwork references its
// gradients as url(#id) — a raw "#" would truncate the data URI fragment.
const uri = `data:image/svg+xml,${encodeURIComponent(composed)}`;

const out =
    `// Generated by scripts/generate-firefox-port-badge.mjs — do not edit by hand.\n` +
    `// Fuses the Mozilla Firefox logo (scripts/firefox-logo.svg) with the RoValra\n` +
    `// mark (public/Assets/icon-128.png) into one CSP-safe data: URI badge icon.\n` +
    `export const FIREFOX_PORT_BADGE_ICON = ${JSON.stringify(uri)};\n`;

writeFileSync(
    join(root, 'src/content/core/configs/firefoxPortBadgeIcon.js'),
    out,
);
// Standalone copy for eyeballing the composition in a browser/screenshot.
writeFileSync(join(root, 'scripts/firefox-port-badge.preview.svg'), composed);

console.log(
    `firefoxPortBadgeIcon.js ${(out.length / 1024).toFixed(1)} KB, ` +
        `uri ${uri.length} chars`,
);
